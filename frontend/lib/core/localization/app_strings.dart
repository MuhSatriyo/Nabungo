  static String tr(String key, {String locale = 'id', Map<String, String>? params}) {
    final langMap = _strings[locale] ?? _strings['id']!;
    String? value = langMap[key];
    if (value == null) {
      final fallback = _strings['id']?[key];
      if (fallback != null) return _interpolate(fallback, params);
      return key;
    }
    return _interpolate(value, params);
  }

  static String _interpolate(String value, Map<String, String>? params) {
    if (params == null || params.isEmpty) return value;
    String result = value;
    params.forEach((k, v) {
      result = result.replaceAll('{$k}', v);
    });
    return result;
  }

